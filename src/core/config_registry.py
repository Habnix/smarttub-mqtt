DEPRECATED_BY_ENV = {
    option.env_name: option
    for option in CONFIG_OPTIONS
    if option.status == "deprecated"
}
DEPRECATED_BY_YAML = {
    option.yaml_path: option
    for option in CONFIG_OPTIONS
    if option.status == "deprecated"
}


def render_reviewed_configuration_reference() -> str:
    """Render the checked-in reference from the registry."""
    lines = [
        "<!-- Generated by scripts/generate_config_reference.py; do not edit. -->",
        "# Reviewed configuration options",
        "",
        "This reference covers the options audited in project-analysis item P1-02.",
        "Deprecated options are accepted for one compatibility cycle, emit a warning,",
        "and have no runtime effect.",
        "",
        "| Environment | YAML path | Default | Validation | Status | Description / migration |",
        "|---|---|---:|---|---|---|",
    ]
    for option in CONFIG_OPTIONS:
        details = option.description
        if option.replacement:
            details = f"{details} {option.replacement}"
        lines.append(
            "| "
            + " | ".join(
                (
                    f"`{option.env_name}`",
                    f"`{option.yaml_path}`",
                    f"`{option.default}`",
                    option.validator,
                    option.status,
                    details,
                )
            )
            + " |"
        )
    lines.append("")
    return "\n".join(lines)
