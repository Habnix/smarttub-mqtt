"""Machine-readable metadata for configuration options under compatibility review."""

from __future__ import annotations

from dataclasses import dataclass
from typing import Literal


@dataclass(frozen=True)
class ConfigOption:
    """Describe one public configuration option and its support status."""

    env_name: str
    yaml_path: str
    default: str
    validator: str
    description: str
    status: Literal["active", "deprecated"] = "active"
    replacement: str | None = None


